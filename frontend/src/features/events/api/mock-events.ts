// Rolling demo dates keep the core discovery examples upcoming on every fresh page load.
// Venues and bookings are fictional; cities and street names are Montenegro-inspired.
function schedule(days: number, hour: number, duration = 3) {
  const startsAt = new Date()
  startsAt.setUTCDate(startsAt.getUTCDate() + days)
  startsAt.setUTCHours(hour, 0, 0, 0)
  return {
    startsAt: startsAt.toISOString(),
    endsAt: new Date(startsAt.getTime() + duration * 3600000).toISOString(),
  }
}
