begin;
create extension if not exists pgtap with schema extensions;
set local search_path=public,extensions;
select plan(22);
select has_table('private','event_reports','Reports exist');
select has_table('private','moderation_audit','Moderation audit exists');
select has_table('private','event_report_attempts','Durable report limiter exists');
select ok((select relrowsecurity from pg_class where oid='private.event_reports'::regclass),'Reports use RLS');
select ok((select relrowsecurity from pg_class where oid='private.moderation_audit'::regclass),'Audit uses RLS');
select ok((select relrowsecurity from pg_class where oid='private.event_report_attempts'::regclass),'Limiter uses RLS');
select is(has_table_privilege('authenticated','private.event_reports','SELECT,INSERT,UPDATE,DELETE'),false,'No direct client reports');
select is(has_table_privilege('authenticated','private.moderation_audit','SELECT,INSERT,UPDATE,DELETE,TRUNCATE'),false,'No direct client audit');
select is(has_table_privilege('rollcall_moderation_executor','private.moderation_audit','UPDATE,DELETE,TRUNCATE'),false,'Executor cannot rewrite audits');
select is(has_column_privilege('rollcall_moderation_executor','public.events','host_id','UPDATE'),false,'Executor cannot change hosts');
select is(has_column_privilege('rollcall_moderation_executor','public.events','title','UPDATE'),false,'Executor cannot rewrite content');
select is(has_table_privilege('rollcall_moderation_executor','private.event_locations','SELECT'),false,'No exact addresses');
select is(has_table_privilege('rollcall_moderation_executor','private.event_invitations','SELECT'),false,'No invitation secrets');
select is(has_table_privilege('rollcall_moderation_executor','private.profile_private','SELECT'),false,'No private age');
select is(has_schema_privilege('rollcall_moderation_executor','auth','USAGE'),false,'No raw Auth access');
select is(pg_has_role('authenticated','rollcall_moderation_executor','MEMBER'),false,'Clients cannot assume executor');
select is((select rolcanlogin from pg_roles where rolname='rollcall_moderation_executor'),false,'Executor cannot log in');
select is((select rolbypassrls from pg_roles where rolname='rollcall_moderation_executor'),false,'Executor cannot bypass RLS');
select is(has_function_privilege('anon','public.submit_event_report(uuid,text,text)','EXECUTE'),false,'Anonymous report denied');
select is(has_function_privilege('rollcall_moderation_executor','private.my_permissions()','EXECUTE'),true,'Executor can check current trusted permissions');
select is(has_function_privilege('rollcall_moderation_executor','private.valid_event_tags(text[],text)','EXECUTE'),true,'Cancellation can enforce unchanged event constraints');
select throws_ok('truncate private.moderation_audit','42501','Role audit is append-only.','Moderation audit truncate blocked');
select * from finish();
rollback;
